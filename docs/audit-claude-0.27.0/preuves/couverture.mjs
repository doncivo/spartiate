// AUDIT-CLAUDE-0.27.0 : génère couverture.md depuis la liste des fichiers du tag et lectures.tsv.
// Usage (racine du worktree) : node docs/audit-claude-0.27.0/preuves/couverture.mjs
// Jamais branché sur la CI.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const DIR = 'docs/audit-claude-0.27.0';
const TAG = 'v0.27.0';
const files = execSync(`git ls-tree -r --name-only ${TAG} -- src src-tauri scripts .github/workflows`, { encoding: 'utf8' })
  .split('\n').filter(Boolean);

const codex = /^(src\/db\/|src\/sync\/|src\/domain\/sync\/|src-tauri\/src\/sync\/)/;
const isTest = (f) => /\.(test|spec)\.(ts|tsx|mjs|js)$/.test(f) || /\/__tests__\//.test(f) || /\.snap$/.test(f)
  || /^src-tauri\/tests\//.test(f) || /(TestKit|testPreload|todayTestPreload)\.ts$/.test(f) && false;
const hors = [
  [/^src-tauri\/vendor\//, 'vendored (plugin SQL et sqlx-sqlite), hors relecture : code tiers figé, garde propre au dépôt relue en 8a'],
  [/^src-tauri\/permissions\/autogenerated\//, 'généré par tauri-build, hors relecture : contenu dérivé des commandes relues en 8a'],
  [/^src-tauri\/gen\//, 'généré, hors relecture'],
  [/^src-tauri\/icons\//, 'binaire (icône), hors relecture'],
  [/\.(png|jpg|jpeg|ico|icns|svg|woff2?|gif)$/, 'binaire, hors relecture'],
  [/\.gitkeep$/, 'fichier vide'],
];

const rules = [
  [/^src\/domain\/(training|cardio|bodyProfile|bodyProgress)/, '4'],
  [/^src\/domain\/(nutrition|supplement)/, '5'],
  [/^src\/domain\/(recovery|health|recoveryNotificationPlan)/, '6'],
  [/^src\/platform\/(healthkit)/, '6'],
  [/^src\/platform\/(off|barcode|ocr|photoImage)/, '5'],
  [/^src\/features\/(app\/Today|app\/ErgoToday|training|cardio|strength|recovery)/, '7a'],
  [/^src\/i18n\/(fr\.)?(training|today|timer|workout|routine|strength|cardio|circuit|progression|recovery)/i, '7a'],
  [/^src\/features\/(nutrition|bodyProgress)/, '7b'],
  [/^src\/i18n\/(fr\.)?(nutrition|recipes|supplement|scan|body|capture)/i, '7b'],
  [/^src-tauri\/(plugins|ios)\//, '8b'],
  [/^src-tauri\/Info\.ios\.plist$/, '8b'],
  [/^scripts\/ios\//, '8b'],
  [/^src-tauri\//, '8a'],
  [/^(\.github\/workflows|scripts)\//, '11'],
  [/^src\/platform\//, '8b'],
  [/^src\//, '7c'],
];

const lect = new Map();
if (existsSync(`${DIR}/preuves/lectures.tsv`)) {
  for (const line of readFileSync(`${DIR}/preuves/lectures.tsv`, 'utf8').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [f, partie, date, par, note] = line.split('\t');
    lect.set(f, { partie, date, par, note: note ?? '' });
  }
}

const rows = [];
let prod = 0, lus = 0, horsN = 0, tests = 0, codexN = 0;
for (const f of files) {
  if (codex.test(f)) { codexN++; continue; }
  if (isTest(f)) { tests++; continue; }
  const h = hors.find(([re]) => re.test(f));
  if (h) { horsN++; rows.push(`| \`${f}\` | — | hors relecture | ${h[1]} |`); continue; }
  prod++;
  const partie = rules.find(([re]) => re.test(f))?.[1] ?? '7c';
  const l = lect.get(f);
  if (l) lus++;
  rows.push(`| \`${f}\` | ${l?.partie ?? partie} | ${l ? `lu ${l.date} (${l.par})` : 'à lire'} | ${l?.note ?? ''} |`);
}
const inconnus = [...lect.keys()].filter((f) => !files.includes(f));

const out = `# AUDIT-CLAUDE-0.27.0 — couverture

Généré par \`preuves/couverture.mjs\` depuis \`git ls-tree ${TAG}\` et \`preuves/lectures.tsv\` : ne pas éditer à la main.

- Fichiers de production et d'outillage du périmètre : **${prod}**, lus : **${lus}** (${prod ? ((100 * lus) / prod).toFixed(1) : 0} %).
- Hors relecture motivée (vendored, généré, binaire) : ${horsN}. Tests et supports (partie 11, hors décompte) : ${tests}.
- Dossiers de Codex exclus (src/db, src/sync, src/domain/sync, src-tauri/src/sync) : ${codexN}.
${inconnus.length ? `- Entrées de lectures.tsv absentes du tag : ${inconnus.join(', ')}\n` : ''}
| Fichier | Partie | Statut | Note |
|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(`${DIR}/couverture.md`, out);
console.log(JSON.stringify({ prod, lus, horsN, tests, codexN, inconnus: inconnus.length }));
